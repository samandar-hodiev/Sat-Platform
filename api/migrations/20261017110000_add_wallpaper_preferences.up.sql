-- Dashboard wallpaper (session 2.11, PRD §4.4–4.5): a separate choice for Light and Dark mode,
-- each "none", a built-in gallery pattern or the learner's own uploaded image, plus opacity and
-- blur shared by both. One uploaded image per mode: a new upload replaces the old one. The
-- uploaded image stays stored (wallpaper_*_key) while the learner tries a gallery pattern, so
-- they can switch back without uploading again; removing it clears the key.
-- Gallery ids are checked against the API's allow-list; the database only checks the format.
BEGIN;

ALTER TABLE user_preferences
    ADD COLUMN wallpaper_light_source     TEXT NOT NULL DEFAULT 'none',
    ADD COLUMN wallpaper_light_gallery_id TEXT,
    ADD COLUMN wallpaper_light_key        TEXT,
    ADD COLUMN wallpaper_dark_source      TEXT NOT NULL DEFAULT 'none',
    ADD COLUMN wallpaper_dark_gallery_id  TEXT,
    ADD COLUMN wallpaper_dark_key         TEXT,
    -- How strongly the wallpaper shows through the page background, in percent. Capped at 80 so
    -- page text on the background always keeps a tint of the canvas colour behind it.
    ADD COLUMN wallpaper_opacity          SMALLINT NOT NULL DEFAULT 40,
    -- Gaussian blur radius in CSS pixels.
    ADD COLUMN wallpaper_blur             SMALLINT NOT NULL DEFAULT 0,

    ADD CONSTRAINT user_preferences_wallpaper_light_source_check
        CHECK (wallpaper_light_source IN ('none', 'gallery', 'custom')),
    ADD CONSTRAINT user_preferences_wallpaper_dark_source_check
        CHECK (wallpaper_dark_source IN ('none', 'gallery', 'custom')),
    -- A gallery id is stored exactly when the source is the gallery.
    ADD CONSTRAINT user_preferences_wallpaper_light_gallery_check
        CHECK ((wallpaper_light_source = 'gallery') = (wallpaper_light_gallery_id IS NOT NULL)
            AND (wallpaper_light_gallery_id IS NULL OR wallpaper_light_gallery_id ~ '^[a-z0-9-]{1,32}$')),
    ADD CONSTRAINT user_preferences_wallpaper_dark_gallery_check
        CHECK ((wallpaper_dark_source = 'gallery') = (wallpaper_dark_gallery_id IS NOT NULL)
            AND (wallpaper_dark_gallery_id IS NULL OR wallpaper_dark_gallery_id ~ '^[a-z0-9-]{1,32}$')),
    -- "custom" needs an uploaded image; keys are generated by the API (never a file name).
    ADD CONSTRAINT user_preferences_wallpaper_light_key_check
        CHECK ((wallpaper_light_source <> 'custom' OR wallpaper_light_key IS NOT NULL)
            AND (wallpaper_light_key IS NULL
                OR wallpaper_light_key ~ '^wallpapers/[0-9a-f-]{36}/[0-9a-f]{32}\.jpg$')),
    ADD CONSTRAINT user_preferences_wallpaper_dark_key_check
        CHECK ((wallpaper_dark_source <> 'custom' OR wallpaper_dark_key IS NOT NULL)
            AND (wallpaper_dark_key IS NULL
                OR wallpaper_dark_key ~ '^wallpapers/[0-9a-f-]{36}/[0-9a-f]{32}\.jpg$')),
    ADD CONSTRAINT user_preferences_wallpaper_opacity_check
        CHECK (wallpaper_opacity BETWEEN 10 AND 80),
    ADD CONSTRAINT user_preferences_wallpaper_blur_check
        CHECK (wallpaper_blur BETWEEN 0 AND 20);

COMMIT;
